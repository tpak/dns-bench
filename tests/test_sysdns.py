from __future__ import annotations

import unittest
from pathlib import Path
from unittest import mock

from dnsbench import sysdns

# Real `scutil --dns` output from macOS 27 (the first section, then the start of the scoped one).
SCUTIL = """\
DNS configuration

resolver #1
  search domain[0] : lan
  nameserver[0] : 192.168.8.1
  nameserver[1] : fe80::1
  if_index : 15 (en0)
  flags    : Request A records
  reach    : 0x00020002 (Reachable,Directly Reachable Address)

resolver #2
  domain   : local
  options  : mdns
  timeout  : 5
  flags    : Request A records
  reach    : 0x00000000 (Not Reachable)
  order    : 300000

resolver #3
  domain   : 254.169.in-addr.arpa
  options  : mdns
  nameserver[0] : 10.9.9.9

DNS configuration (for scoped queries)

resolver #1
  search domain[0] : lan
  nameserver[0] : 192.168.99.99
  if_index : 15 (en0)
"""

RESOLV_CONF = """\
# Generated by NetworkManager
search lan
options edns0 trust-ad
nameserver 192.0.2.53 # the router
nameserver 2001:db8::53
nameserver 192.0.2.53
; nameserver 192.0.2.99
"""

STUB_RESOLV_CONF = "# This is /run/systemd/resolve/stub-resolv.conf\nnameserver 127.0.0.53\noptions edns0\n"


def reader(files: dict[Path, str]):
    return lambda path: files.get(path)


class ParseTest(unittest.TestCase):
    def test_scutil_takes_the_default_resolver_only(self):
        # Blocks with a domain (mDNS, split DNS) and the scoped section are left out. A link-local server
        # gets its block's interface, since it can't be reached without one.
        self.assertEqual(sysdns.parse_scutil(SCUTIL), ["192.168.8.1", "fe80::1%en0"])

    def test_scutil_never_mixes_in_a_second_default_resolver(self):
        # A full-tunnel VPN can add a second domain-less block: that's another network's resolver.
        text = (
            "DNS configuration\n\nresolver #1\n  domain   : local\n  nameserver[0] : 10.9.9.9\n\n"
            "resolver #2\n  search domain[0] : lan\n\n"  # no servers: not the one
            "resolver #3\n  nameserver[0] : 192.168.1.1\n  if_index : 15 (en0)\n\n"
            "resolver #4\n  nameserver[0] : 10.8.0.1\n  if_index : 20 (utun3)\n"
        )
        self.assertEqual(sysdns.parse_scutil(text), ["192.168.1.1"])

    def test_scutil_keeps_a_zone_it_already_has(self):
        text = "DNS configuration\n\nresolver #1\n  nameserver[0] : fe80::1%en1\n  if_index : 15 (en0)\n"
        self.assertEqual(sysdns.parse_scutil(text), ["fe80::1%en1"])

    def test_scutil_without_resolvers(self):
        self.assertEqual(sysdns.parse_scutil("No DNS configuration available\n"), [])

    def test_resolv_conf(self):
        self.assertEqual(sysdns.parse_resolv_conf(RESOLV_CONF), ["192.0.2.53", "2001:db8::53", "192.0.2.53"])


class DetectTest(unittest.TestCase):
    def test_macos_uses_scutil(self):
        found = sysdns.detect("darwin", run_scutil=lambda: SCUTIL, read=reader({}))
        self.assertEqual(found, sysdns.Detected(["192.168.8.1", "fe80::1%en0"], "scutil --dns"))

    def test_macos_falls_back_to_resolv_conf(self):
        for output in (None, "DNS configuration\n\nresolver #1\n  nameserver[0] : 127.0.0.1\n"):
            with self.subTest(output=output):
                found = sysdns.detect(
                    "darwin", run_scutil=lambda o=output: o, read=reader({sysdns.RESOLV_CONF: RESOLV_CONF})
                )
                self.assertEqual(found.servers, ["192.0.2.53", "2001:db8::53"])
                self.assertEqual(found.source, "/etc/resolv.conf")

    def test_linux_reads_resolv_conf_and_never_runs_scutil(self):
        def no_scutil():
            raise AssertionError("scutil is macOS only")

        found = sysdns.detect("linux", run_scutil=no_scutil, read=reader({sysdns.RESOLV_CONF: RESOLV_CONF}))
        self.assertEqual(found, sysdns.Detected(["192.0.2.53", "2001:db8::53"], "/etc/resolv.conf"))

    def test_systemd_stub_is_skipped_for_its_upstream_servers(self):
        files = {
            sysdns.RESOLV_CONF: STUB_RESOLV_CONF,
            sysdns.SYSTEMD_RESOLV_CONF: "nameserver 192.0.2.1\nnameserver 127.0.0.1\n",
        }
        found = sysdns.detect("linux", read=reader(files))
        self.assertEqual(found.servers, ["192.0.2.1"])
        self.assertEqual(found.source, "/run/systemd/resolve/resolv.conf")
        self.assertEqual(found.skipped, ["127.0.0.53", "127.0.0.1"])

    def test_a_loopback_stub_alone_is_reported_not_used(self):
        found = sysdns.detect("linux", read=reader({sysdns.RESOLV_CONF: STUB_RESOLV_CONF}))
        self.assertEqual(found, sysdns.Detected([], "/etc/resolv.conf", ["127.0.0.53"]))
        self.assertEqual(
            found.describe_empty(), "/etc/resolv.conf lists only 127.0.0.53, which can't be benchmarked"
        )

    def test_unusable_entries_are_skipped(self):
        text = "nameserver ::1\nnameserver fe80::1\nnameserver not-an-ip\nnameserver fe80::2%eth0\n"
        found = sysdns.detect("linux", read=reader({sysdns.RESOLV_CONF: text}))
        self.assertEqual(found.servers, ["fe80::2%eth0"])
        self.assertEqual(found.skipped, ["::1", "fe80::1", "not-an-ip"])

    def test_nothing_readable(self):
        found = sysdns.detect("linux", read=reader({}))
        self.assertEqual(found, sysdns.Detected([]))
        self.assertEqual(found.describe_empty(), "this system's DNS settings could not be read")
        found = sysdns.detect("linux", read=reader({sysdns.RESOLV_CONF: "search lan\n"}))
        self.assertEqual(found.describe_empty(), "/etc/resolv.conf lists no DNS servers")

    def test_a_missing_scutil_is_not_an_error(self):
        with mock.patch.object(sysdns.subprocess, "run", side_effect=FileNotFoundError("scutil")):
            self.assertIsNone(sysdns._run_scutil())
        with mock.patch.object(
            sysdns.subprocess, "run", side_effect=sysdns.subprocess.TimeoutExpired("scutil", 5)
        ):
            self.assertIsNone(sysdns._run_scutil())


if __name__ == "__main__":
    unittest.main()
